  "https://about.starbucks.com/stories/2025/ways-to-customize-your-beverage-at-starbucks/";
function modification(
  id: string,
  phrase: string,
  field: Modification["field"],
  code: string,
  source: string,
  extra: Partial<Modification["mark"]> = {},
): Modification {
  return {
    id,
    phrase,
    field,
    source,
    mark: {
      code,
      meaning: lookup(field, code).meaning,
      reason: phrase,
      ...extra,
    },
  };
}
